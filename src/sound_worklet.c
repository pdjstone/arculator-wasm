/*Arculator 2.2 by Sarah Walker
  Sound emulation, AudioWorklet version. Used by the wasm build instead of
  sound.c.

  The filtering and resampling to 48kHz that sound.c does is done by the
  AudioWorklet (frontend/audio-dsp.js), which is sent the VIDC's samples as they
  are fetched (see sound_ring.h and sound_emscripten.c). This file keeps the
  sound DMA and only the bookkeeping that says where in that stream things
  happen: how many output frames sound.c would have generated by now, counted
  from the start of the stream. It steps through each 50ms block the way
  update_sound() in sound.c does, so that audio dumps and clock changes line up
  exactly with it. Keep the two in step.*/
#include <math.h>
#include <string.h>
#include "arc.h"
#include "arm.h"
#include "config.h"
#include "ioc.h"
#include "memc.h"
#include "plat_sound.h"
#include "sound.h"
#include "sound_ring.h"
#include "timer.h"

int stereoimages[8];
int stereo;
int soundena;
int sound_gain = 0;

static emu_timer_t sound_timer;
static emu_timer_t sound_timer_100ms;
static uint64_t sound_timer_base_period; /*Time for 1 tick of sample base clock*/

static int SAMP_INC;

static int sample_period;
static uint64_t sample_16_time; /*Time for 16 bytes (1 fetch) to be consumed by VIDC*/

static int sound_first_poll = 1;
static int sound_write_ptr;
static uint32_t sound_block_counter; /*50ms blocks since sound_init(), used to time audio dumps deterministically*/

static uint32_t sound_out_base;  /*Output frames in the 50ms blocks completed since the stream started*/
static int sound_stream_valid;   /*The worklet has been sent a RESET and is following the stream*/
static uint32_t sound_unflushed_ticks; /*Base clock ticks sent since the last sound_stream_flush()*/

static int sound_clock_mhz;
int sound_filter;

static double filter_freqs[] =
{
	2200.0, /*Original filter*/
	3200.0, /*Reduced*/
	5000.0  /*More reduced*/
};

static int16_t log_to_lin[256];

static int vollevels[2][2][8]=
{
	{
		{0,4,4,4,4,4,4,4},
		{0,4,4,4,4,4,4,4}
	},
	{
		{0,6,5,4,3,2,1,0},
		{0,0,1,2,3,4,5,6}
	}
};

/*The worklet's filter coefficients. They're made here rather than in JS, as
  JS's Math.tan() can differ from tan() here in the last bit*/
static double ACoef[3];
static double BCoef[3];

static void iir_gen_coefficients(const int samplerate, const double cutoff, double* const ax, double* const by)
{
	double ff = cutoff/samplerate;
	const double ita = 1.0 / tan(M_PI*ff);
	const double q = sqrt(2.0);

	ax[0] = 1.0 / (1.0 + q*ita + ita*ita);
	ax[1]= 2*ax[0];
	ax[2]= ax[0];
	by[0] = 1.0;
	by[1] = -(2.0 * (ita*ita - 1.0) * ax[0]);
	by[2] = (1.0 - q*ita + ita*ita) * ax[0];
}

/*Steps through each 50ms block exactly as update_sound() in sound.c does,
  without the filtering and resampling. sound_write_ptr is the number of output
  frames generated so far in the block*/
static void update_sound(int end_sample)
{
	if (end_sample > 2400)
		end_sample = 2400;

	if (sound_first_poll)
		return;
	if (!soundena)
		return;

	if (sound_write_ptr < end_sample)
		sound_write_ptr = end_sample;
}

/*Audio dumping. The worklet captures the 48kHz stereo frames that sound.c
  would have handed to the audio device (before gain and disc noise), so that
  audio from the different backends can be compared. Here we only decide where
  the dump starts: the first output frame of the 50ms block with the right
  block counter. The worklet sends the finished dump to the main thread, which
  makes the WAV file (frontend/emu-audio.js).*/
#define AUDIO_DUMP_RATE 48000

static uint32_t audio_dump_start_block;
static uint32_t audio_dump_target_frames;

void sound_dump_audio(double delay, double duration)
{
	int state = sound_dev_get_dump_state();

	if (state == AUDIO_DUMP_WAITING || state == AUDIO_DUMP_RECORDING)
	{
		rpclog("sound_dump_audio: a dump is already in progress\n");
		return;
	}
	if (!(duration > 0.0))
	{
		rpclog("sound_dump_audio: duration must be greater than zero\n");
		sound_dev_set_dump_state(AUDIO_DUMP_OFF);
		return;
	}

	audio_dump_target_frames = (uint32_t)(duration * AUDIO_DUMP_RATE);
	/*Time the dump against the 50ms block counter rather than
	  total_emulation_millis: that only updates when arc_run() returns, so
	  keying on it can shift the start position by up to one arc_run chunk
	  between runs*/
	if (delay < 0.0)
		delay = 0.0;
	audio_dump_start_block = sound_block_counter + (uint32_t)(delay * 20.0);

	sound_dev_set_dump_state(AUDIO_DUMP_WAITING);

	rpclog("sound_dump_audio: dumping %.3fs starting at %.3fs\n", duration, delay);
}

int sound_get_dump_state(void)
{
	return sound_dev_get_dump_state();
}

/*Called at the end of each 50ms block. The dump starts with the next block,
  which is the one sound.c would start with, so it is announced now, when
  sound_out_base is the index of its first frame and the worklet can't have got
  there yet. (It can't be announced part way through a block, as the worklet
  may already have played the start of it. So with a delay of less than 0.1s
  the dump starts a block later than sound.c's would.) That only works if the
  next block has real audio in it, hence the checks for the stale first block
  after the stream starts. The worklet only captures audio while the
  AudioContext is running, so unlike sound.c's dump this waits until it is.*/
static void audio_dump_poll(void)
{
	if (sound_dev_get_dump_state() != AUDIO_DUMP_WAITING)
		return;
	if (!soundena || sound_first_poll || !sound_stream_valid)
		return;
	if (sound_block_counter + 1 < audio_dump_start_block)
		return;

	/*Before the event, as the worklet may report FINISHED or ERROR as soon as
	  it sees it*/
	sound_dev_set_dump_state(AUDIO_DUMP_RECORDING);
	if (!sound_dev_dump(sound_out_base, audio_dump_target_frames))
		sound_dev_set_dump_state(AUDIO_DUMP_WAITING);
}

/*The output frame, within the current 50ms block, that emulated time has
  reached. May be more than 2400 if the block's timer is overdue*/
static int block_end_sample(void)
{
	uint64_t remaining = timer_get_remaining_u64(&sound_timer_100ms);
	int remaining_samples = (int)(((remaining / (50ull * 1000ull)) * 2400ull) / TIMER_USEC);

	return 2400 - remaining_samples;
}

/*(Re)start the stream the worklet is following. This is what sound_enable(1)
  does in sound.c: the first 50ms block after it is stale, and the output
  stream starts again from the beginning of the next. Also done whenever the
  AudioContext starts running, as the worklet has missed everything up to then*/
static void sound_stream_reset(void)
{
	sound_first_poll = 1;
	sound_write_ptr = 0;
	sound_out_base = 0;
	sound_stream_valid = 0;

	if (sound_dev_live())
	{
		sound_dev_reset(SAMP_INC, sound_clock_mhz, ACoef, BCoef);
		sound_stream_valid = 1;
	}
}

/*The output frame that the emulation has reached: the frames in the blocks
  that have finished, plus how far through the current block it is. Events are
  only ever sent for frames at or after this, because sound_set_clock() and the
  end of each block are the only things that move it forwards and they never
  go backwards. Before the first full block there are no frames at all.*/
uint32_t sound_stream_frame_position(void)
{
	int frame = sound_write_ptr;

	if (!sound_first_poll && soundena)
	{
		/*Where sound_set_clock() would put a clock change made now*/
		int end_sample = block_end_sample();

		if (end_sample > 2400)
			end_sample = 2400;
		if (end_sample > frame)
			frame = end_sample;
	}
	return sound_out_base + frame;
}

#define SOUND_FLUSH_PER_SEC 200 /*Publish to the worklet at least every 5ms of emulated time*/

int sound_stream_active(void)
{
	return soundena && sound_stream_valid;
}

uint32_t sound_stream_tick_position(void)
{
	uint64_t remaining = timer_get_remaining_u64(&sound_timer);

	return sound_dev_ticks_written() - (uint32_t)(remaining / sound_timer_base_period);
}

/*Called for each VIDC sound DMA fetch with its 16 stereo samples*/
static void sound_stream_poll(const int16_t *samples)
{
	if (!sound_dev_live())
		sound_stream_valid = 0;
	else if (soundena && !sound_stream_valid)
		sound_stream_reset();

	if (soundena && sound_stream_valid)
	{
		/*If the ring overflowed, the stream has a hole in it, so start again*/
		if (!sound_dev_record(sample_period, samples))
		{
			sound_stream_valid = 0;
			return;
		}

		/*arc_run() can take a long time when the emulated machine is busy, so
		  don't make the worklet wait for it to finish*/
		sound_unflushed_ticks += 16 * sample_period;
		if (sound_unflushed_ticks >= (uint32_t)sound_clock_mhz / SOUND_FLUSH_PER_SEC)
			sound_stream_flush();
	}
}

/*Make what has been sent since the last call visible to the worklet. Called
  after each arc_run() and every few ms of emulated time, which saves calling
  into JS for every DMA fetch: the worklet only looks every few ms anyway*/
void sound_stream_flush(void)
{
	sound_unflushed_ticks = 0;
	if (sound_stream_valid)
		sound_dev_flush(sound_stream_frame_position());
}

static void pollsound_100ms(void *p)
{
	timer_advance_u64(&sound_timer_100ms, 50 * 1000 * TIMER_USEC);
	sound_block_counter++;

	update_sound(2400);
	if (soundena && sound_first_poll)
		sound_first_poll = 0;

	sound_out_base += sound_write_ptr;
	sound_write_ptr = 0;
	audio_dump_poll();
}

/*Whether the coefficients are different from a saved copy*/
static int coefs_changed(const double *a_coef, const double *b_coef)
{
	return memcmp(a_coef, ACoef, sizeof(ACoef)) || memcmp(b_coef, BCoef, sizeof(BCoef));
}

void sound_set_clock(int clock_mhz)
{
	int old_samp_inc = SAMP_INC;
	double old_a_coef[3], old_b_coef[3];

	memcpy(old_a_coef, ACoef, sizeof(ACoef));
	memcpy(old_b_coef, BCoef, sizeof(BCoef));

	/*Write out samples up to this point*/
	update_sound(block_end_sample());

	/*Update constants for new clock frequency*/
	sound_timer_base_period = (TIMER_USEC * 1000000) / clock_mhz;
	sample_16_time = sample_period * 16 * sound_timer_base_period;
	SAMP_INC = ((int)(((double)clock_mhz / 48000.0) * 16384.0));

	iir_gen_coefficients(clock_mhz, filter_freqs[sound_filter], ACoef, BCoef);

	sound_clock_mhz = clock_mhz;

	/*RISC OS rewrites the clock select (IOEB) register a lot, mostly with the
	  same value. That changes nothing here or in sound.c, so don't send it: at
	  boot it can be hundreds of times a second, which fills the event ring.
	  If the event can't be sent, the worklet would carry on with the old
	  clock, so start the stream again*/
	if (sound_stream_valid && (SAMP_INC != old_samp_inc || coefs_changed(old_a_coef, old_b_coef)) &&
	    !sound_dev_clock(sound_out_base + sound_write_ptr, SAMP_INC, sound_clock_mhz, ACoef, BCoef))
		sound_stream_valid = 0;
}

void sound_update_filter(void)
{
	double old_a_coef[3], old_b_coef[3];

	memcpy(old_a_coef, ACoef, sizeof(ACoef));
	memcpy(old_b_coef, BCoef, sizeof(BCoef));

	iir_gen_coefficients(sound_clock_mhz, filter_freqs[sound_filter], ACoef, BCoef);

	/*As in sound_set_clock()*/
	if (sound_stream_valid && coefs_changed(old_a_coef, old_b_coef) && !sound_dev_filter(ACoef, BCoef))
		sound_stream_valid = 0;
}

void sound_set_period(int period)
{
	sample_period = period;
	sample_16_time = period * 16 * sound_timer_base_period;
}

static void pollsound(void *p)
{
	uint8_t in_samples[16];
	int16_t samples[32];
	int c;

	timer_advance_u64(&sound_timer, sample_16_time);

	/*Read in new samples*/
	if (sdmaena)
	{
		memcpy(in_samples, &ram[(spos & 0x7fff0) >> 2], 16);
		memc_dma_sound_req_ts = tsc;
		memc_dma_sound_req = 1;
		recalc_min_timer();
	}
	else
		memset(in_samples, 0, 16);

	/*The worklet does the upsampling to the VIDC frequency*/
	for (c = 0; c < 16; c++)
	{
		int16_t sample = log_to_lin[in_samples[c]];

		samples[c*2]     = sample * vollevels[stereo][0][stereoimages[c & 7]];
		samples[c*2 + 1] = sample * vollevels[stereo][1][stereoimages[c & 7]];
	}
	sound_stream_poll(samples);

	if (sdmaena)
	{
		if (spos == ssend)
		{
			if (nextvalid == 2)
			{
				spos = sstart2 = sstart << 2;
				ssend = sendN << 2;
				nextvalid = 0;
			}
			else
				spos = sstart2;
			ioc_irqb(IOC_IRQB_SOUND_BUFFER);
		}
		else
			spos += 16;
	}
}

static signed short convbyte(uint8_t v)
{
	int sign, point, chord;
	signed short temp;

	//                         7C       chord = 3     p = E/14
	if (fdctype == FDC_WD1793_A500)
	{
		sign = v & 0x80;
		point = v & 0xf;
		chord = (v >> 4) & 7;
	}
	else
	{
		sign = v & 1;
		point = (v >> 1) & 0xf;
		chord = v >> 5;

	}

	temp = (1 << (chord + 4)) - (1 << 4);
	temp += (point << chord);
	return sign ? - temp : temp;
}

void sound_enable(int enable)
{
	soundena = enable;
	if (enable)
		sound_stream_reset();
	else
		sound_stream_valid = 0;
}

void sound_init(void)
{
	int c;

	for (c = 0; c < 256; c++)
		log_to_lin[c] = convbyte(c);

	timer_add(&sound_timer, pollsound, NULL, 1);
	timer_add(&sound_timer_100ms, pollsound_100ms, NULL, 1);
	sound_first_poll = 1;
	sound_block_counter = 0;
	SAMP_INC = ((int)((1000000.0 / 48000.0) * 16384.0));

	sound_out_base = 0;
	sound_write_ptr = 0;
	sound_stream_valid = 0;
}
